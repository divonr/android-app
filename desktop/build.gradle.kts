// The code sandbox's key and URL are not in the sources: they come from local.properties
// (gitignored: sandbox.apiKey, sandbox.executorUrl) or from the build's environment, as a
// generated constant. A build without the key succeeds; the tool then reports that it is not
// configured.
val generateSandboxConfig by tasks.registering {
    val localProperties = Properties().apply {
        val file = rootProject.file("local.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }
    fun setting(property: String, env: String, default: String = ""): String =
        (localProperties.getProperty(property) ?: System.getenv(env) ?: default).trim()
    fun String.asKotlinLiteral(): String =
        "\"" + replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

    val apiKey = setting("sandbox.apiKey", "SANDBOX_API_KEY").asKotlinLiteral()
    val executorUrl = setting("sandbox.executorUrl", "SANDBOX_EXECUTOR_URL", "https://api-divonr.xyz/v2/execute").asKotlinLiteral()
    val outputDir = layout.buildDirectory.dir("generated/sandbox/kotlin")
    inputs.property("apiKey", apiKey)
    inputs.property("executorUrl", executorUrl)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("com/example/ApI/desktop/SandboxBuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package com.example.ApI.desktop\n\n" +
                "/** Generated by the build (desktop/build.gradle.kts); never committed. */\n" +
                "internal object SandboxBuildConfig {\n" +
                "    const val API_KEY = $apiKey\n" +
                "    const val EXECUTOR_URL = $executorUrl\n" +
                "}\n"
        )
    }
}

kotlin.sourceSets.named("main") {
    kotlin.srcDir(generateSandboxConfig)
}


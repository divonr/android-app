// Regenerates app/src/main/assets/emoji/emoji.tsv (the Android emoji keyboard's dataset)
// from emojibase-data. Usage, from a directory where `npm install emojibase-data` was run:
//   node /path/to/scripts/generate_emoji_asset.mjs /path/to/app/src/main/assets/emoji/emoji.tsv
//
// Format: "@<category id>" starts a category; every other line is
//   <emoji> TAB <name>|<keyword>|... TAB <skin-tone variants, space separated (may be empty)>
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import path from 'node:path'

const require = createRequire(path.join(process.cwd(), 'noop.js'))
const data = require('emojibase-data/en/data.json')
const version = require('emojibase-data/package.json').version

// emojibase group number -> keyboard category, in the keyboard's tab order
const categories = [
  ['smileys_people', [0, 1]],
  ['animals_nature', [3]],
  ['food_drink', [4]],
  ['activities', [6]],
  ['travel_places', [5]],
  ['objects', [7]],
  ['symbols', [8]],
  ['flags', [9]],
]

const clean = (s) => s.toLowerCase().replace(/[\t\n|]/g, ' ').trim()
const lines = [`# Generated by scripts/generate_emoji_asset.mjs from emojibase-data ${version} (MIT). Do not edit.`]
for (const [id, groups] of categories) {
  lines.push(`@${id}`)
  const emojis = data
    .filter((e) => groups.includes(e.group) && typeof e.order === 'number')
    .sort((a, b) => a.order - b.order)
  for (const e of emojis) {
    const words = [...new Set([clean(e.label), ...(e.tags ?? []).map(clean)])].filter(Boolean)
    // Only the five uniform skin tones; mixed-tone combinations are left out
    const skins = (e.skins ?? []).filter((s) => typeof s.tone === 'number').map((s) => s.emoji)
    lines.push(`${e.emoji}\t${words.join('|')}\t${skins.join(' ')}`)
  }
}
writeFileSync(process.argv[2], lines.join('\n') + '\n')
console.log(`${lines.length} lines written`)

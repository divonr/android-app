/**
 * A message that only carries files has an empty text: nothing stands in for it on a screen
 * or in a request, whether the chat was stored with the old stand-in text or without it.
 */
class FileOnlyMessagesTest {

    @TempDir
    lateinit var dir: File

    private val hebrew = "[קובץ מצורף]"
    private val english = "[Attached file]"

    private fun attached(name: String, mimeType: String): Attachment {
        val file = File(dir, name).apply { writeText("content of $name") }
        return Attachment(local_file_path = file.absolutePath, file_name = name, mime_type = mimeType)
    }

    /** A file this machine does not have (generated by a cloud run, attached on another device). */
    private fun remote(name: String, mimeType: String) = Attachment(file_name = name, mime_type = mimeType, sha256 = "a".repeat(64), size = 3)

    private fun sandboxCall(id: String, signature: String? = null) = listOf(
        Message(
            role = "tool_call", text = "", toolCallId = id,
            toolCall = ToolCallInfo(
                ToolRegistry.PYTHON_INTERPRETER, "workspace_sandbox", buildJsonObject { put("code", "run $id") },
                ToolExecutionResult.Success("saved"), "2026-01-01T00:00:00Z", signature
            )
        ),
        Message(role = "tool_response", text = "saved", toolResponseCallId = id, toolResponseOutput = "saved")
    )

    /**
     * One chat in the shapes a sandbox turn is stored in: files after a call that no text
     * follows (between two calls, and as the whole reply), files on a text, and a user who sends
     * files without a text. [fileOnly] is the text such a message was stored with, by index.
     */
    private fun chat(fileOnly: (Int) -> String): List<Message> = (listOf(
        Message(role = "user", text = "Make a chart"),
    ) + sandboxCall("call-1", signature = "sig") + listOf(
        Message(role = "assistant", text = fileOnly(0), attachments = listOf(remote("chart.png", "image/png")), model = "m"),
    ) + sandboxCall("call-2") + listOf<Message>(
        Message(role = "assistant", text = fileOnly(1), attachments = listOf(remote("data.csv", "text/csv")), model = "m"),
        Message(role = "user", text = fileOnly(2), attachments = listOf(remote("notes.docx", "application/msword"))),
        Message(role = "assistant", text = "Here is **the summary**", attachments = listOf(remote("summary.pdf", "application/pdf")), model = "m"),
        Message(role = "user", text = fileOnly(3), attachments = listOf(attached("photo.png", "image/png"))),
        Message(role = "assistant", text = "A photo"),
    )).let { messages -> messages.mapIndexed { index, message -> message.copy(id = "m$index") } }

    private val stored by lazy { chat { "" } }
    private val legacy by lazy { chat { listOf(hebrew, " $hebrew\n", english, hebrew)[it] } }

    /** Every string a request carries, by the key it is under. */
    private fun strings(element: JsonElement, key: String? = null, into: MutableList<Pair<String?, String>> = mutableListOf()): List<Pair<String?, String>> {
        when (element) {
            is JsonObject -> element.forEach { (k, v) -> strings(v, k, into) }
            is JsonArray -> element.forEach { strings(it, key, into) }
            is JsonNull -> {}
            is JsonPrimitive -> if (element.isString) into += key to element.content
        }
        return into
    }

    /** The request is the same for both ways the chat was stored, says no stand-in and has no empty text. */
    private fun <T : JsonElement> serialised(build: suspend (List<Message>) -> List<T>): List<T> = runBlocking {
        val request = build(stored.forProvider())
        assertEquals(request, build(legacy.forProvider()), "a legacy chat is sent like a new one")
        assertEquals(request, build(stored.forProvider()), "the same chat gives the same request")
        val all = strings(JsonArray(request))
        assertTrue(all.none { (_, value) -> "קובץ מצורף" in value || value.trim() == english }, "no stand-in text: $all")
        assertTrue(all.none { (key, value) -> key in setOf("text", "content", "output") && value.isBlank() }, "no empty text: $all")
        request.forEach { turn ->
            val content = (turn as? JsonObject)?.get("content") ?: (turn as? JsonObject)?.get("parts")
            assertFalse(content is JsonArray && content.isEmpty(), "no empty turn: $turn")
        }
        request
    }

    private fun JsonObject.string(key: String) = getValue(key).jsonPrimitive.content
    private fun JsonObject.types(key: String = "content") = getValue(key).jsonArray.map { it.jsonObject.string("type") }

    @Test
    fun `a stand-in text counts as no text only on a user or assistant message with files`() {
        val file = listOf(remote("a.txt", "text/plain"))
        for (text in listOf(hebrew, english, "  $hebrew ", "$english\n")) {
            assertTrue(FileOnlyMessages.isPlaceholder(text))
            assertEquals("", Message(role = "assistant", text = text, attachments = file).displayText)
            assertEquals("", Message(role = "user", text = text, attachments = file).displayText)
            // Without files it is what the user typed
            assertEquals(text, Message(role = "user", text = text).displayText)
            assertEquals(text, Message(role = "tool_response", text = text, attachments = file).displayText)
        }
        for (text in listOf("", "See $hebrew", "$hebrew.", "[attached file]", "Chart")) {
            assertFalse(FileOnlyMessages.isPlaceholder(text))
            assertEquals(text, Message(role = "assistant", text = text, attachments = file).displayText)
        }
    }

    @Test
    fun `a preview is the text, and the names of the files for a message that only carries files`() {
        val files = listOf(remote("chart.png", "image/png"), remote("data.csv", "text/csv"))
        assertEquals("📎 chart.png, data.csv", Message(role = "assistant", text = "", attachments = files).previewText)
        assertEquals("📎 chart.png, data.csv", Message(role = "assistant", text = hebrew, attachments = files).previewText)
        assertEquals("📎 chart.png, data.csv", Message(role = "user", text = english, attachments = files).previewText)
        assertEquals("Look", Message(role = "user", text = "Look", attachments = files).previewText)
        assertEquals("", Message(role = "assistant", text = "").previewText)
    }

    @Test
    fun `a provider is given neither a stand-in nor an assistant message that says nothing`() {
        val sent = legacy.forProvider()
        assertEquals(sent, stored.forProvider())
        assertEquals(
            listOf("user", "tool_call", "tool_response", "tool_call", "tool_response", "user", "assistant", "user", "assistant"),
            sent.map { it.role }
        )
        assertEquals(listOf("Make a chart", "", "Here is **the summary**", "", "A photo"), sent.filter { !it.isToolCall && !it.isToolResponse }.map { it.text })
        // The files stay on the user's messages; a message that needs no change is the same object
        assertEquals(listOf("notes.docx"), sent[5].attachments.map { it.file_name })
        assertSame(stored[0], stored.forProvider()[0])
        assertSame(legacy[8], sent[6])

        // An assistant message that only has thoughts stays (Anthropic replays them before a tool call)
        val thinking = Message(role = "assistant", text = "", thoughts = "Let me run it", thoughtsSignature = "sig")
        assertEquals(listOf(thinking), listOf(thinking).forProvider())
        // An empty reply is not a turn
        assertEquals(emptyList(), listOf(Message(role = "assistant", text = " ")).forProvider())
    }

    @Test
    fun `Anthropic gets no empty text block and no empty turn`() {
        val request = serialised { AnthropicProvider().buildMessages(it) }
        assertEquals(
            listOf("user", "assistant", "user", "assistant", "user", "user", "assistant", "user", "assistant"),
            request.map { it.string("role") }
        )
        assertEquals(listOf("tool_use"), request[1].types())
        assertEquals(listOf("tool_use"), request[3].types())
        // A file that is not sent, on a turn without a text: the turn names it
        assertEquals("""[Attached file: "notes.docx"]""", request[5].getValue("content").jsonArray.single().jsonObject.string("text"))
        // An image that is sent, on a turn without a text: the image alone
        assertEquals(listOf("image"), request[7].types())

        // Thoughts before a tool call are replayed without a text block; alone they are no turn
        val thinking = Message(role = "assistant", text = "", thoughts = "Let me run it", thoughtsSignature = "sig")
        val withCall = runBlocking { AnthropicProvider().buildMessages(listOf(thinking) + sandboxCall("call-9")) }
        assertEquals(listOf("thinking", "tool_use"), withCall.first().types())
        assertEquals(emptyList(), runBlocking { AnthropicProvider().buildMessages(listOf(thinking)) })
    }

    @Test
    fun `OpenAI gets no assistant item without text and no empty text part`() {
        val request = serialised { OpenAIProvider().buildInput(it, "") }
        assertEquals(
            listOf("user", "function_call", "function_call_output", "function_call", "function_call_output", "user", "assistant", "user", "assistant"),
            request.map { it["role"]?.jsonPrimitive?.content ?: it.string("type") }
        )
        // The file is not on this machine: nothing of it can be sent, so the turn names it
        assertEquals("""[Attached file: "notes.docx"]""", request[5].getValue("content").jsonArray.single().jsonObject.string("text"))
        assertEquals(listOf("input_image"), request[7].types())
    }

    @Test
    fun `the OpenAI-compatible providers get no assistant message without text or tool calls`() {
        for (provider in listOf(OpenRouterProvider(), LLMStatsProvider())) {
            val request = serialised { provider.buildMessages(it, "").map { message -> message.jsonObject } }
            assertEquals(
                listOf("user", "assistant", "tool", "assistant", "tool", "user", "assistant", "user", "assistant"),
                request.map { it.string("role") }
            )
            for (index in listOf(1, 3)) {
                assertEquals(JsonNull, request[index].getValue("content"))
                assertEquals(1, request[index].getValue("tool_calls").jsonArray.size)
            }
            assertEquals("""[Attached file: "notes.docx"]""", request[5].string("content"))
            assertEquals(listOf("image_url"), request[7].types())
        }
    }

    @Test
    fun `Cohere gets no assistant message without text or tool calls`() {
        val request = serialised { CohereProvider().buildMessages(it, "") }
        assertEquals(
            listOf("user", "assistant", "tool", "assistant", "tool", "user", "assistant", "user", "assistant"),
            request.map { it.string("role") }
        )
        assertFalse("content" in request[1] || "content" in request[3])
        assertEquals("""[Attached file: "notes.docx"]""", request[5].getValue("content").jsonArray.single().jsonObject.string("text"))
        assertEquals(listOf("image_url"), request[7].types())
    }

    @Test
    fun `Poe gets no bot message without text and a user turn that names its files`() {
        val request = serialised { PoeProvider().buildMessages(it, "", false, ThinkingBudgetValue.None) }
        assertEquals(listOf("user", "user", "bot", "user", "bot"), request.map { it.string("role") })
        assertEquals("""[Attached file: "notes.docx"]""", request[1].string("content"))
        assertEquals(1, request[1].getValue("attachments").jsonArray.size)
        assertEquals("""[Attached file: "photo.png"]""", request[3].string("content"))
    }

    @Test
    fun `Google gets no empty part, and files between two calls of one step do not split it`() {
        for (platform in GooglePlatform.entries) {
            val request = serialised { GoogleProvider(platform).buildContents(it, "") }
            val calls = request.filter { it.string("role") == "model" }
                .map { turn -> turn.getValue("parts").jsonArray.count { "functionCall" in it.jsonObject } }
            // The signed call and its unsigned sibling are one model turn again
            assertEquals(listOf(2, 0, 0), calls, platform.name)
            val users = request.filter { it.string("role") == "user" && it.getValue("parts").jsonArray.none { part -> "functionResponse" in part.jsonObject } }
            assertEquals(3, users.size)
            assertTrue("notes.docx" in users[1].getValue("parts").jsonArray.first().jsonObject.string("text"))
        }
    }

    @Test
    fun `a template provider gets no assistant turn without text and a user turn that names its files`() {
        val provider = FullDynamicCustomProvider(
            FullCustomProviderConfig(
                name = "Mine", providerKey = "fullcustom_mine", baseUrl = "http://127.0.0.1:1", defaultModel = "m",
                bodyTemplate = "{}",
                messageFields = MessageFieldsConfig(userField = MessageFieldConfig("messages", """{"role":"user","content":"{prompt}"}"""))
            )
        )
        val sent = provider.templateMessages(stored.forProvider())
        assertEquals(sent, provider.templateMessages(legacy.forProvider()))
        assertEquals(
            listOf("Make a chart", """[Attached file: "notes.docx"]""", "Here is **the summary**", """[Attached file: "photo.png"]""", "A photo"),
            sent.filter { it.role == "user" || it.role == "assistant" }.map { it.text }
        )
        val thinking = Message(role = "assistant", text = "", thoughts = "hm")
        assertEquals(emptyList(), provider.templateMessages(listOf(thinking)))
    }
}
